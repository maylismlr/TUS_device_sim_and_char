function focus_mm = parse_focus_z_from_filename(filename)
%PARSE_FOCUS_Z_FROM_FILENAME
%
% Extract commanded Z focus from filenames such as:
%
%   3mpfus 3 zLine Focus X 0mm Y 0mm Z 90mm.fig
%
% Decimal and negative values are also accepted.

    token = regexpi( ...
        filename, ...
        'Focus.*?Z\s*([+-]?\d+(?:\.\d+)?)\s*mm', ...
        'tokens', ...
        'once');


    if isempty(token)

        error( ...
            ['Could not extract commanded focal depth from filename:\n' ...
             '%s'], ...
             filename);

    end


    focus_mm = ...
        str2double(token{1});

end


function [x, y] = read_profile_from_fig(filepath)
%READ_PROFILE_FROM_FIG
%
% Open a MATLAB .fig invisibly and extract the line object that contains
% the largest number of valid X/Y samples.
%
% For the supplied hydrophone figures, this should correspond to the
% measured pressure trace.
%
% No digitization is performed: these are the original XData and YData
% values stored in the .fig.

    fig = ...
        openfig( ...
            filepath, ...
            'invisible');


    cleanup_object = ...
        onCleanup( ...
            @() close(fig)); %#ok<NASGU>


    lines = ...
        findobj( ...
            fig, ...
            'Type', ...
            'line');


    if isempty(lines)

        error( ...
            ['No MATLAB line object found in:\n' ...
             '%s'], ...
             filepath);

    end


    % Number of valid paired X/Y samples for every line object

    n_valid = ...
        zeros(numel(lines), 1);


    for line_ind = 1:numel(lines)

        this_x = ...
            double( ...
                lines(line_ind).XData(:));

        this_y = ...
            double( ...
                lines(line_ind).YData(:));


        n = ...
            min( ...
                numel(this_x), ...
                numel(this_y));


        if n == 0
            continue;
        end


        this_x = ...
            this_x(1:n);

        this_y = ...
            this_y(1:n);


        n_valid(line_ind) = ...
            sum( ...
                isfinite(this_x) ...
                & isfinite(this_y));

    end


    [~, best_line_ind] = ...
        max(n_valid);


    x = ...
        double( ...
            lines(best_line_ind).XData(:));

    y = ...
        double( ...
            lines(best_line_ind).YData(:));


    % Ensure equal length

    n = ...
        min( ...
            numel(x), ...
            numel(y));


    x = x(1:n);
    y = y(1:n);


    % Remove invalid samples

    valid = ...
        isfinite(x) ...
        & isfinite(y);


    x = x(valid);
    y = y(valid);


    if numel(x) < 2

        error( ...
            ['Too few valid data samples extracted from:\n' ...
             '%s'], ...
             filepath);

    end


    % Sort by increasing z

    [x, sort_ind] = ...
        sort(x);


    y = ...
        y(sort_ind);


    % If repeated z values exist, average their pressure values.

    [x_unique, ~, group_ind] = ...
        unique(x);


    if numel(x_unique) < numel(x)

        y = ...
            accumarray( ...
                group_ind, ...
                y, ...
                [], ...
                @mean);


        x = ...
            x_unique;

    end

end


function [p_peak, z_peak] = find_focal_peak( ...
    z, ...
    p, ...
    commanded_focus, ...
    search_fraction, ...
    minimum_z, ...
    smoothing_points)
%FIND_FOCAL_PEAK
%
% Find the pressure maximum in a search region surrounding the commanded
% focal depth.
%
% The same procedure is applied to hydrophone and simulation data.
%
% smoothing_points = 1:
%       no smoothing.
%
% smoothing_points > 1:
%       moving-mean smoothing is used for peak detection.

    z = z(:);
    p = p(:);


    z_min = ...
        max( ...
            minimum_z, ...
            search_fraction(1) ...
            * commanded_focus);


    z_max = ...
        search_fraction(2) ...
        * commanded_focus;


    valid = ...
        isfinite(z) ...
        & isfinite(p) ...
        & z >= z_min ...
        & z <= z_max;


    if ~any(valid)

        error( ...
            ['No samples exist inside focal search window ' ...
             '[%.2f, %.2f] mm.'], ...
             z_min * 1e3, ...
             z_max * 1e3);

    end


    z_search = ...
        z(valid);

    p_search = ...
        p(valid);


    % Optional smoothing for peak detection

    if smoothing_points > 1

        p_for_peak = ...
            smoothdata( ...
                p_search, ...
                'movmean', ...
                smoothing_points);

    else

        p_for_peak = ...
            p_search;

    end


    [~, local_peak_ind] = ...
        max(p_for_peak);


    % Use the ORIGINAL pressure value at the selected position.
    %
    % Thus smoothing, if enabled, affects only which point is considered
    % the focal peak; it does not alter the reported pressure amplitude.

    z_peak = ...
        z_search(local_peak_ind);

    p_peak = ...
        p_search(local_peak_ind);

end