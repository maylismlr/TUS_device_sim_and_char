%% fit_element_size_profile.m
%
% Effective element-size calibration using measured hydrophone z-line scans.
%
% For every candidate effective element size:
%
%   1. Build the known 256-element TRUST geometry with fixed physical pitch.
%   2. Simulate all commanded focal depths available in the hydrophone data.
%   3. Extract the simulated on-axis pressure profile p(z).
%   4. Compare simulated and measured profile SHAPES using relative L2 error:
%
%       L2 = ||p_sim_norm - p_hyd_norm||_2 / ||p_hyd_norm||_2
%
%      where EACH profile is independently normalized by its own maximum.
%
%   5. Extract simulated and measured focal peak positions and calculate
%      the absolute axial focal-position error [mm].
%
%   6. Compare focal-pressure depth dependence. Since the simulation uses an
%      arbitrary source pressure, both measured and simulated peak-pressure
%      curves are normalized at 30 mm:
%
%          p_norm(z_f) = p_peak(z_f) / p_peak(30 mm)
%
%      and the relative pressure error is:
%
%          epsilon_p = 100 * |p_sim_norm - p_hyd_norm| / p_hyd_norm
%
%      The 30 mm reference point is excluded from the mean because its
%      residual is zero by construction.
%
%   7. Output a summary table analogous in structure to Table 1 of
%      Martin et al., containing for every tested element size:
%
%          - mean normalized focal-pressure error [%]
%          - mean axial focal-position error [mm]
%          - mean relative L2 profile error
%
%   8. Plots as a check but end plots for thesis are plotted in
%   replot_element_size_calibration.m (Figures 3.2 and 3.3, as well as
%   Supp. Figures 6.8 and 6.9).
%
% IMPORTANT:
%
%   - The input source pressure remains arbitrary.
%   - No absolute source-amplitude calibration is performed here.
%   - No focal-delay/focal-depth correction is performed here.
%   - Element size is selected ONLY by minimum mean L2 profile error.
%
% author: Maylis Mueller


clearvars;
close all;
clc;


% =========================================================================
% PATHS
% =========================================================================

addpath('/data/hu_muellerm/MATLAB Add-Ons/Collections/k-Wave/k-Wave');
addpath('/data/tu_muellerm/utils');

hydrophone_dir = '/data/tu_muellerm_cloud/Fraunhofer_data/';


% =========================================================================
% HYDROPHONE FILE SELECTION
% =========================================================================
%
% Example filename:
%
%   3mpfus 3 zLine Focus X 0mm Y 0mm Z 90mm.fig
%
% If all relevant measurements belong to the "3mpfus 3" series, keep:
%
%   '3mpfus 3*zLine*Focus X 0mm Y 0mm Z *mm.fig'
%
% If the relevant folder contains ONLY the wanted z-line measurements,
% this can instead be:
%
%   '*zLine*Focus X 0mm Y 0mm Z *mm.fig'
%
% IMPORTANT:
% All files entering the normalized peak-pressure comparison should have
% been acquired using the same excitation voltage/settings.

file_pattern = ...
    '3mpfus 3*zLine*Focus X 0mm Y 0mm Z *mm.fig';


% =========================================================================
% HYDROPHONE UNITS
% =========================================================================
%   x-axis = z position [mm]
%   y-axis = sound pressure Pmax [kPa]

hydro_z_scale = 1e-3;      % mm  -> m
hydro_p_scale = 1e3;       % kPa -> Pa


% =========================================================================
% METRIC OPTIONS
% =========================================================================

% Reference commanded focal depth for normalized peak-pressure comparison.
pressure_reference_focus_mm = 30;


% -------------------------------------------------------------------------
% Focal peak search window
% -------------------------------------------------------------------------
%
% Only used to determine p_peak and z_peak.
%
% This prevents very proximal near-field maxima from being mistaken for
% the intended focus.
%
% Example:
%   for a commanded 90 mm focus:
%
%       0.65*90 = 58.5 mm
%       1.25*90 = 112.5 mm
%
% The delay/focus calibration is NOT changed here.

focus_search_fraction = [0.65, 1.25];

minimum_focus_search_z = 5e-3;      % [m]


% -------------------------------------------------------------------------
% L2 profile comparison region
% -------------------------------------------------------------------------
%
% false:
%   compare the complete hydrophone z-line wherever measurement and
%   simulation overlap.
%
% true:
%   compare only the focal search window above.
%
% Since the goal here is to use the measured profile scans, start with
% false.

l2_use_focal_window = false;


% =========================================================================
% OPTIONAL PEAK-DETECTION SMOOTHING
% =========================================================================
%
% A value of 1 means NO smoothing.
%
% If hydrophone scans later show isolated noisy points causing unstable peak
% locations, this could be increased to e.g. 3 or 5.
%
% The same setting is applied to BOTH measured and simulated profiles when
% determining peak position and peak amplitude.

peak_smoothing_points = 3;


% =========================================================================
% LOAD HYDROPHONE DATA
% =========================================================================

files = dir(fullfile(hydrophone_dir, file_pattern));

if isempty(files)

    error( ...
        ['No hydrophone .fig files were found.\n\n' ...
         'Directory:\n%s\n\n' ...
         'Pattern:\n%s'], ...
         hydrophone_dir, ...
         file_pattern);

end


fprintf('\n');
fprintf('============================================================\n');
fprintf('HYDROPHONE DATA\n');
fprintf('============================================================\n');
fprintf('Directory: %s\n', hydrophone_dir);
fprintf('Pattern:   %s\n', file_pattern);
fprintf('Files found: %d\n\n', numel(files));


hydro = struct( ...
    'filename', {}, ...
    'focus_mm', {}, ...
    'z', {}, ...
    'p', {}, ...
    'p_peak', {}, ...
    'z_peak', {} );


for file_ind = 1:numel(files)

    filename = files(file_ind).name;

    filepath = fullfile( ...
        files(file_ind).folder, ...
        filename);


    % ---------------------------------------------------------------------
    % Extract commanded Z focus from filename
    % ---------------------------------------------------------------------

    focus_mm = ...
        parse_focus_z_from_filename(filename);


    % ---------------------------------------------------------------------
    % Read original XData / YData directly from the MATLAB figure
    % ---------------------------------------------------------------------

    [z_raw, p_raw] = ...
        read_profile_from_fig(filepath);


    % Convert units

    z = z_raw * hydro_z_scale;       % [m]
    p = p_raw * hydro_p_scale;       % [Pa]


    % ---------------------------------------------------------------------
    % Extract measured focal peak
    % ---------------------------------------------------------------------

    [p_peak, z_peak] = ...
        find_focal_peak( ...
            z, ...
            p, ...
            focus_mm * 1e-3, ...
            focus_search_fraction, ...
            minimum_focus_search_z, ...
            peak_smoothing_points);


    % Store
    hydro(file_ind).filename = filename;
    hydro(file_ind).focus_mm = focus_mm;
    hydro(file_ind).z        = z(:);
    hydro(file_ind).p        = p(:);
    hydro(file_ind).p_peak   = p_peak;
    hydro(file_ind).z_peak   = z_peak;


    fprintf( ...
        '%2d/%2d | Focus %6.1f mm | peak %8.2f kPa | z_peak %7.2f mm\n', ...
        file_ind, ...
        numel(files), ...
        focus_mm, ...
        p_peak / 1e3, ...
        z_peak * 1e3);

end


% =========================================================================
% SORT HYDROPHONE DATA BY COMMANDED FOCUS
% =========================================================================

[~, sort_ind] = sort([hydro.focus_mm]);

hydro = hydro(sort_ind);

n_scans = numel(hydro);


% =========================================================================
% UNIQUE FOCAL DEPTHS
% =========================================================================
%
% If several hydrophone scans exist at the same commanded focal depth, the
% expensive acoustic simulation is still performed only once.

focus_values_mm = ...
    unique([hydro.focus_mm], 'sorted');

focus_values = ...
    focus_values_mm * 1e-3;

n_focus = numel(focus_values_mm);


fprintf('\nUnique commanded focal depths [mm]:\n');

disp(focus_values_mm);


% Map every hydrophone scan onto the corresponding simulation index.
hydro_focus_ind = nan(n_scans, 1);

for scan_ind = 1:n_scans

    focus_ind = find( ...
        abs( ...
            focus_values_mm ...
            - hydro(scan_ind).focus_mm ...
        ) < 1e-9, ...
        1);

    if isempty(focus_ind)

        error( ...
            'Could not map hydrophone scan to focal-depth list.');

    end

    hydro_focus_ind(scan_ind) = focus_ind;

end


% =========================================================================
% CHECK 30 mm PRESSURE REFERENCE EXISTS
% =========================================================================

pressure_reference_ind = find( ...
    abs( ...
        focus_values_mm ...
        - pressure_reference_focus_mm ...
    ) < 1e-9, ...
    1);


if isempty(pressure_reference_ind)

    error( ...
        ['No hydrophone measurement exists at the requested pressure ' ...
         'reference depth of %.1f mm.\n' ...
         'Available depths are:\n%s'], ...
         pressure_reference_focus_mm, ...
         mat2str(focus_values_mm));

end


% =========================================================================
% ARRAY GEOMETRY
% =========================================================================

row_counts = ...
    [6 10 12 14 16 16 18 18 18 ...
     18 18 18 16 16 14 12 10 6];


assert( ...
    sum(row_counts) == 256, ...
    'row_counts must contain exactly 256 elements.');


% Physical pitch: FIXED.
element_pitch = 3.08e-3;        % [m]


% Physical element size, reference only.
element_size_nominal = 2.58e-3; % [m]


% =========================================================================
% ACOUSTIC PARAMETERS
% =========================================================================

f0 = 0.48e6;        % [Hz]
c0 = 1480;          % [m/s]


% =========================================================================
% COMPUTATIONAL GRID
% =========================================================================

dx = 0.25e-3;       % [m]


x_size = 64e-3;
y_size = 64e-3;
z_size = 150e-3;


Nx = round(x_size / dx) + 1;
Ny = round(y_size / dx) + 1;
Nz = round(z_size / dx) + 1;


% Ensure x = 0 and y = 0 are exactly represented.

if rem(Nx, 2) == 0
    Nx = Nx + 1;
end

if rem(Ny, 2) == 0
    Ny = Ny + 1;
end


x_vec = ...
    ((0:Nx-1) - floor(Nx/2)) * dx;

y_vec = ...
    ((0:Ny-1) - floor(Ny/2)) * dx;

z_vec = ...
    (0:Nz-1) * dx;


% Evaluation time

t_eval = 160e-6;       % [s]


fprintf('\n');
fprintf('============================================================\n');
fprintf('SIMULATION GRID\n');
fprintf('============================================================\n');

fprintf( ...
    'Grid: %d x %d x %d\n', ...
    Nx, Ny, Nz);

fprintf( ...
    'Physical size: %.1f x %.1f x %.1f mm\n', ...
    range(x_vec) * 1e3, ...
    range(y_vec) * 1e3, ...
    range(z_vec) * 1e3);

fprintf( ...
    'dx = %.3f mm\n', ...
    dx * 1e3);

fprintf( ...
    'Evaluation time = %.0f us\n', ...
    t_eval * 1e6);


% =========================================================================
% ELEMENT-SIZE SEARCH RANGE
% =========================================================================

element_size_values_mm = 2.58 : 0.5 : 3.08;

element_size_values = ...
    element_size_values_mm * 1e-3;


n_size = ...
    numel(element_size_values);


% =========================================================================
% SOURCE AMPLITUDE
% =========================================================================
%
% ARBITRARY.
%
% acousticFieldPropagator is linear, so this value is irrelevant for:
%
%   - independently normalized L2 profiles
%   - peak-pressure ratios normalized at 30 mm
%   - focal position
%
% Absolute amplitude calibration comes later.

source_amp_test = 1;       % [Pa]


% =========================================================================
% OUTPUT FILES
% =========================================================================

output_mat = ...
    'afp_element_size_fit_hydrophone.mat';

output_summary_csv = ...
    'afp_element_size_error_table.csv';

output_detailed_csv = ...
    'afp_element_size_error_by_focus.csv';


% =========================================================================
% PREALLOCATE SIMULATION RESULTS
% =========================================================================

simulated_peak_pressure = ...
    nan(n_size, n_focus);

simulated_peak_z = ...
    nan(n_size, n_focus);


% Store only the on-axis pressure profile rather than every 3-D field.

simulated_axial_pressure = ...
    nan(n_size, n_focus, Nz);


% Grid indices nearest x = y = 0

[~, x0] = min(abs(x_vec));
[~, y0] = min(abs(y_vec));


% =========================================================================
% ELEMENT SIZE SWEEP
% =========================================================================

sweep_timer = tic;


for size_ind = 1:n_size

    element_size = ...
        element_size_values(size_ind);


    fprintf('\n');
    fprintf('============================================================\n');
    fprintf( ...
        'ELEMENT SIZE %d/%d: %.3f mm\n', ...
        size_ind, ...
        n_size, ...
        element_size * 1e3);
    fprintf('============================================================\n');


    % ---------------------------------------------------------------------
    % Element-centre positions
    % ---------------------------------------------------------------------

    [~, positions] = ...
        build_karray( ...
            row_counts, ...
            element_size, ...
            element_size, ...
            element_pitch, ...
            0);


    % Check aperture fits transverse domain.
    aperture_half = ...
        max( ...
            max(abs(positions(:, 1))), ...
            max(abs(positions(:, 2))) ...
        ) ...
        + element_size / 2;


    if aperture_half > max(x_vec)
        warning( ...
            ['Aperture half-width %.2f mm exceeds transverse ' ...
             'domain half-width %.2f mm. Candidate skipped.'], ...
             aperture_half * 1e3, ...
             max(x_vec) * 1e3);

        continue;

    end


    % =====================================================================
    % SIMULATE EVERY MEASURED COMMANDED FOCUS
    % =====================================================================

    for focus_ind = 1:n_focus

        focal_depth = ...
            focus_values(focus_ind);


        fprintf( ...
            '  Focus %6.1f mm ... ', ...
            focal_depth * 1e3);


        % -----------------------------------------------------------------
        % Build BLI source
        % -----------------------------------------------------------------
        [amp_in, phase_in] = ...
            build_afp_source_bli( ...
                positions, ...
                element_size, ...
                source_amp_test, ...
                x_vec, ...
                y_vec, ...
                z_vec, ...
                focal_depth, ...
                f0, ...
                c0);


        % -----------------------------------------------------------------
        % Propagate
        % -----------------------------------------------------------------
        pressure = ...
            acousticFieldPropagator( ...
                amp_in, ...
                phase_in, ...
                dx, ...
                f0, ...
                c0, ...
                'Time', ...
                t_eval);


        % -----------------------------------------------------------------
        % Extract only on-axis amplitude
        % -----------------------------------------------------------------
        axial_pressure = ...
            abs( ...
                squeeze( ...
                    pressure(x0, y0, :) ...
                ) ...
            ); % because complex pressure, need to do abs


        clear pressure amp_in phase_in;


        simulated_axial_pressure( ...
            size_ind, ...
            focus_ind, ...
            :) = axial_pressure;


        % -----------------------------------------------------------------
        % Simulated focal peak
        % -----------------------------------------------------------------

        [p_peak, z_peak] = ...
            find_focal_peak( ...
                z_vec(:), ...
                axial_pressure(:), ...
                focal_depth, ...
                focus_search_fraction, ...
                minimum_focus_search_z, ...
                peak_smoothing_points);


        simulated_peak_pressure( ...
            size_ind, ...
            focus_ind) = p_peak;

        simulated_peak_z( ...
            size_ind, ...
            focus_ind) = z_peak;


        fprintf( ...
            'peak %.5g Pa at %.2f mm\n', ...
            p_peak, ...
            z_peak * 1e3);

    end


    % ---------------------------------------------------------------------
    % Save intermediate results after every candidate
    % ---------------------------------------------------------------------

    save( ...
        output_mat, ...
        'element_size_values_mm', ...
        'element_pitch', ...
        'element_size_nominal', ...
        'focus_values_mm', ...
        'hydro', ...
        'simulated_peak_pressure', ...
        'simulated_peak_z', ...
        'simulated_axial_pressure', ...
        'z_vec', ...
        'dx', ...
        'f0', ...
        'c0', ...
        't_eval', ...
        '-v7.3');

end


fprintf('\n');
fprintf( ...
    'Simulation sweep finished in %.1f min.\n', ...
    toc(sweep_timer) / 60);


% =========================================================================
% METRIC 1:
% RELATIVE L2 ERROR OF NORMALIZED PROFILE SHAPE
% =========================================================================
%
% One value for every:
%
%      element size x hydrophone scan
%
% Each hydrophone and simulated profile is independently normalized by its
% OWN maximum before comparison.

l2_error = ...
    nan(n_size, n_scans);


for size_ind = 1:n_size

    for scan_ind = 1:n_scans

        focus_ind = ...
            hydro_focus_ind(scan_ind);


        % Simulated profile
        p_sim = squeeze( ...
                simulated_axial_pressure( ...
                    size_ind, ...
                    focus_ind, ...
                    :));

        z_sim = z_vec(:);


        % Measured profile
        z_hyd = hydro(scan_ind).z(:);

        p_hyd = hydro(scan_ind).p(:);


        % -----------------------------------------------------------------
        % Interpolate simulation onto hydrophone measurement coordinates
        % -----------------------------------------------------------------
        p_sim_interp = ...
            interp1( ...
                z_sim, ...
                p_sim, ...
                z_hyd, ...
                'linear', ...
                NaN);


        valid = ...
            isfinite(z_hyd) ...
            & isfinite(p_hyd) ...
            & isfinite(p_sim_interp);


        % -----------------------------------------------------------------
        % Optional focal-region-only L2
        % -----------------------------------------------------------------
        if l2_use_focal_window

            focal_depth = ...
                hydro(scan_ind).focus_mm * 1e-3;


            z_min = max( ...
                minimum_focus_search_z, ...
                focus_search_fraction(1) * focal_depth);


            z_max = ...
                focus_search_fraction(2) * focal_depth;


            valid = ...
                valid ...
                & z_hyd >= z_min ...
                & z_hyd <= z_max;
        end


        p_hyd_compare = ...
            p_hyd(valid);

        p_sim_compare = ...
            p_sim_interp(valid);


        if numel(p_hyd_compare) < 2
            warning( ...
                ['Too few overlapping samples for element size %.2f mm, ' ...
                 'file %s.'], ...
                 element_size_values_mm(size_ind), ...
                 hydro(scan_ind).filename);
            continue;
        end


        % -----------------------------------------------------------------
        % Independent normalization by EACH profile's own maximum
        % -----------------------------------------------------------------
        hydro_max = ...
            max(p_hyd_compare);

        sim_max = ...
            max(p_sim_compare);


        if hydro_max <= 0 || sim_max <= 0
            warning( ...
                'Non-positive profile maximum encountered.');
            continue;

        end


        p_hyd_norm_profile = ...
            p_hyd_compare / hydro_max;

        p_sim_norm_profile = ...
            p_sim_compare / sim_max;


        % -----------------------------------------------------------------
        % Relative L2 error
        % -----------------------------------------------------------------

        l2_error(size_ind, scan_ind) = ...
            norm(p_sim_norm_profile ...
                - p_hyd_norm_profile, 2) ...
            / ...
            norm(p_hyd_norm_profile, 2);
    end
end


% =========================================================================
% METRIC 2:
% AXIAL FOCAL POSITION ERROR
% =========================================================================
%
% Because these data are on-axis z-line scans:
%
%     epsilon_position = |z_sim_peak - z_hyd_peak|
%
% [mm]
%
% No delay correction is performed.

focal_position_error_mm = ...
    nan(n_size, n_scans);


for size_ind = 1:n_size
    for scan_ind = 1:n_scans

        focus_ind = ...
            hydro_focus_ind(scan_ind);


        z_sim_peak = ...
            simulated_peak_z( ...
                size_ind, ...
                focus_ind);


        z_hyd_peak = ...
            hydro(scan_ind).z_peak;


        focal_position_error_mm( ...
            size_ind, ...
            scan_ind) = ...
            abs( ...
                z_sim_peak ...
                - z_hyd_peak ...
            ) * 1e3;
    end
end


% =========================================================================
% METRIC 3:
% NORMALIZED FOCAL-PEAK PRESSURE ERROR
% =========================================================================
%
% First average measured peak pressure at each commanded focal depth if
% repeated hydrophone measurements exist.
%
% Then normalize both measured and simulated peak-pressure curves at 30 mm.
%
% The arbitrary simulation source pressure therefore cancels completely.

hydro_peak_by_focus = ...
    nan(1, n_focus);


for focus_ind = 1:n_focus

    scan_mask = ...
        abs( ...
            [hydro.focus_mm] ...
            - focus_values_mm(focus_ind) ...
        ) < 1e-9;


    hydro_peak_by_focus(focus_ind) = ...
        mean( ...
            [hydro(scan_mask).p_peak], ...
            'omitnan');

end


% -------------------------------------------------------------------------
% Hydrophone normalized peak-pressure curve
% -------------------------------------------------------------------------

hydro_peak_norm = ...
    hydro_peak_by_focus ...
    / ...
    hydro_peak_by_focus(pressure_reference_ind);


% -------------------------------------------------------------------------
% Simulated normalized peak-pressure curves
% -------------------------------------------------------------------------

simulated_peak_norm = ...
    nan(n_size, n_focus);


for size_ind = 1:n_size

    simulated_peak_norm(size_ind,:) = ...
        simulated_peak_pressure(size_ind, :) ...
        / ...
        simulated_peak_pressure(size_ind, pressure_reference_ind);

end


% -------------------------------------------------------------------------
% Relative pressure error [%]
% -------------------------------------------------------------------------
peak_pressure_error_pct = ...
    100 ...
    * abs( ...
        simulated_peak_norm ...
        - hydro_peak_norm ...
    ) ...
    ./ hydro_peak_norm;


% -------------------------------------------------------------------------
% Exclude 30 mm from the mean because its error is exactly zero by
% construction.
% -------------------------------------------------------------------------
pressure_error_mask = true(1, n_focus);

pressure_error_mask(pressure_reference_ind) = false;


mean_peak_pressure_error_pct = ...
    mean( ...
        peak_pressure_error_pct( ...
            :, ...
            pressure_error_mask), ...
        2, ...
        'omitnan');


% =========================================================================
% MEAN POSITION AND L2 ERRORS
% =========================================================================

mean_focal_position_error_mm = ...
    mean( ...
        focal_position_error_mm, ...
        2, ...
        'omitnan');


mean_l2_error = ...
    mean( ...
        l2_error, ...
        2, ...
        'omitnan');


% =========================================================================
% SUMMARY TABLE
% =========================================================================
%
% Analogous in structure to Martin et al. Table 1.
%
% Each row = one candidate effective element size.

error_table = ...
    table( ...
        element_size_values_mm(:), ...
        mean_peak_pressure_error_pct, ...
        mean_focal_position_error_mm, ...
        mean_l2_error, ...
        'VariableNames', { ...
            'ElementSize_mm', ...
            'PeakPressureError_pct', ...
            'FocalPositionError_mm', ...
            'RelativeL2Error' ...
        });


fprintf('\n');
fprintf('============================================================\n');
fprintf('ELEMENT-SIZE CALIBRATION RESULTS\n');
fprintf('============================================================\n');
fprintf( ...
    'Pressure reference depth: %.1f mm\n', ...
    pressure_reference_focus_mm);
fprintf( ...
    'Number of hydrophone scans: %d\n\n', ...
    n_scans);


disp(error_table);


% Save table

writetable( ...
    error_table, ...
    output_summary_csv);


% =========================================================================
% BEST ELEMENT SIZE
% =========================================================================
%
% PRIMARY calibration criterion:
%
%                  minimum mean relative L2
%
% Pressure and position errors are reported as independent validation
% metrics and are NOT combined into the objective.

[best_l2, best_size_ind] = ...
    min( ...
        mean_l2_error, ...
        [], ...
        'omitnan');


best_element_size_mm = ...
    element_size_values_mm(best_size_ind);


fprintf('\n');
fprintf('============================================================\n');
fprintf('BEST ELEMENT SIZE FROM PROFILE L2\n');
fprintf('============================================================\n');

fprintf( ...
    'Effective element size       = %.3f mm\n', ...
    best_element_size_mm);

fprintf( ...
    'Mean relative L2 error       = %.5f\n', ...
    mean_l2_error(best_size_ind));

fprintf( ...
    'Mean normalized peak error   = %.3f %%\n', ...
    mean_peak_pressure_error_pct(best_size_ind));

fprintf( ...
    'Mean focal-position error    = %.3f mm\n', ...
    mean_focal_position_error_mm(best_size_ind));


if best_size_ind == 1 || best_size_ind == n_size

    warning( ...
        ['Minimum L2 lies at the edge of the element-size sweep. ' ...
         'Consider extending element_size_values_mm.']);

end


% =========================================================================
% DETAILED RESULTS BY FOCUS
% =========================================================================
%
% This table is useful for seeing whether one particular focal depth is
% dominating the mean errors.
%
% Pressure error is defined per UNIQUE commanded focal depth.
% L2 and position error retain individual hydrophone scans.

detail_element_size_mm = [];
detail_focus_mm        = [];
detail_pressure_error  = [];
detail_position_error  = [];
detail_l2_error        = [];
detail_hyd_peak_norm   = [];
detail_sim_peak_norm   = [];
detail_hyd_peak_z_mm   = [];
detail_sim_peak_z_mm   = [];


for size_ind = 1:n_size

    for focus_ind = 1:n_focus

        scan_mask = ...
            hydro_focus_ind == focus_ind;


        % Average repeated hydrophone scans at this focus for L2 and
        % position reporting.

        mean_position_at_focus = ...
            mean( ...
                focal_position_error_mm( ...
                    size_ind, ...
                    scan_mask), ...
                'omitnan');


        mean_l2_at_focus = ...
            mean( ...
                l2_error( ...
                    size_ind, ...
                    scan_mask), ...
